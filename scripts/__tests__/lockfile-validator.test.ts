import { mkdtemp, readFile, rm, writeFile } from 'fs/promises';
import { tmpdir } from 'os';
import { join } from 'path';
import {
  LockFileValidator,
  findLockfileLoopbackReferences,
  findLoopbackReferences,
  findYarnrcLoopbackReferences,
  parseYarnLockfile,
  validateLockfileStructure,
} from '../components/lockfile-validator';

const REPO_ROOT = join(__dirname, '..', '..');

const CHECKSUM =
  '10c0/ef204ca270011308c3cdbf7da702c0b8220775ea28aec52ddba696443f11afad6e725f5534110f2ef014382ab807b695bb4dcbf307683a0fc6927b3817871f6c';

const VALID_LOCKFILE = `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 10
  cacheKey: 10c0

"@actions/core@npm:^3.0.0":
  version: 3.0.0
  resolution: "@actions/core@npm:3.0.0"
  dependencies:
    "@actions/exec": "npm:^3.0.0"
    undici: "npm:^6.23.0"
  checksum: ${CHECKSUM}
  languageName: node
  linkType: hard

"@esbuild/aix-ppc64@npm:0.25.12, @esbuild/aix-ppc64@npm:^0.25.0":
  version: 0.25.12
  resolution: "@esbuild/aix-ppc64@npm:0.25.12"
  conditions: os=aix & cpu=ppc64
  languageName: node
  linkType: hard

"is-localhost-ip@npm:^2.0.0":
  version: 2.0.0
  resolution: "is-localhost-ip@npm:2.0.0"
  peerDependencies:
    prettier: "*"
  peerDependenciesMeta:
    prettier:
      optional: true
  bin:
    is-localhost-ip: bin/cli.js
  checksum: ${CHECKSUM}
  languageName: node
  linkType: hard

"typescript@patch:typescript@npm%3A^5.1.6#optional!builtin<compat/typescript>":
  version: 5.8.2
  resolution: "typescript@patch:typescript@npm%3A5.8.2#optional!builtin<compat/typescript>::version=5.8.2&hash=5786d5"
  checksum: ${CHECKSUM}
  languageName: node
  linkType: hard

"amplify-data-monorepo@workspace:.":
  version: 0.0.0-use.local
  resolution: "amplify-data-monorepo@workspace:."
  languageName: unknown
  linkType: soft
`;

/**
 * Builds a single-entry lockfile so individual fields can be tampered with.
 */
const lockfileWithEntry = (entry: string) => `__metadata:
  version: 10
  cacheKey: 10c0

${entry}
`;

describe('parseYarnLockfile', () => {
  it('parses the yarn berry lockfile format', () => {
    const parsed = parseYarnLockfile(VALID_LOCKFILE);

    expect(parsed.__metadata).toEqual({ version: '10', cacheKey: '10c0' });
    expect(parsed['@actions/core@npm:^3.0.0']).toEqual({
      version: '3.0.0',
      resolution: '@actions/core@npm:3.0.0',
      dependencies: {
        '@actions/exec': 'npm:^3.0.0',
        undici: 'npm:^6.23.0',
      },
      checksum: CHECKSUM,
      languageName: 'node',
      linkType: 'hard',
    });
    expect(
      parsed['@esbuild/aix-ppc64@npm:0.25.12, @esbuild/aix-ppc64@npm:^0.25.0'],
    ).toMatchObject({ conditions: 'os=aix & cpu=ppc64' });
    expect(parsed['is-localhost-ip@npm:^2.0.0']).toMatchObject({
      peerDependencies: { prettier: '*' },
      peerDependenciesMeta: { prettier: { optional: 'true' } },
      bin: { 'is-localhost-ip': 'bin/cli.js' },
    });
  });

  it('parses the repository yarn.lock', async () => {
    const parsed = parseYarnLockfile(
      await readFile(join(REPO_ROOT, 'yarn.lock'), 'utf-8'),
    );
    expect(Object.keys(parsed).length).toBeGreaterThan(1);
  });

  it.each([
    ['odd indentation', '__metadata:\n   version: 10\n'],
    ['indentation jump', '__metadata:\n    version: 10\n'],
    ['tabs', '__metadata:\n\tversion: 10\n'],
    ['duplicate keys', '__metadata:\n  version: 10\n  version: 11\n'],
    ['missing colon', '__metadata:\n  version 10\n'],
    ['missing space after colon', '__metadata:\n  version:10\n'],
    ['mapping without children', '__metadata:\n"foo@npm:1.0.0":\n'],
    ['flow collections', '__metadata:\n  version: [10]\n'],
    ['list items', '__metadata:\n  - 10\n'],
    ['unterminated quoted key', '"foo@npm:1.0.0:\n  version: 1.0.0\n'],
    ['invalid quoted values', '__metadata:\n  version: "10\n'],
  ])('throws on %s', (_, content) => {
    expect(() => parseYarnLockfile(content)).toThrow(/^line \d+: /);
  });
});

describe('validateLockfileStructure', () => {
  it('accepts a valid lockfile', () => {
    expect(
      validateLockfileStructure(parseYarnLockfile(VALID_LOCKFILE)),
    ).toEqual([]);
  });

  it('requires __metadata with an integer version', () => {
    expect(
      validateLockfileStructure(
        parseYarnLockfile('"foo@npm:1.0.0":\n  version: 1.0.0\n'),
      ).map((v) => v.path),
    ).toContain('__metadata');
    expect(
      validateLockfileStructure(
        parseYarnLockfile('__metadata:\n  version: ten\n'),
      ).map((v) => v.path),
    ).toEqual(['__metadata.version']);
  });

  it.each([
    [
      'missing resolution',
      `"foo@npm:^1.0.0":\n  version: 1.0.0\n  languageName: node\n  linkType: hard`,
      '"foo@npm:^1.0.0" is missing the required "resolution" field',
    ],
    [
      'resolution that is a mapping',
      `"foo@npm:^1.0.0":\n  version: 1.0.0\n  resolution:\n    url: x\n  languageName: node\n  linkType: hard`,
      '"foo@npm:^1.0.0".resolution must be a string, got a mapping',
    ],
    [
      'dependencies that are a string',
      `"foo@npm:^1.0.0":\n  version: 1.0.0\n  resolution: "foo@npm:1.0.0"\n  dependencies: bar\n  languageName: node\n  linkType: hard`,
      '"foo@npm:^1.0.0".dependencies must be a mapping, got a string',
    ],
    [
      'nested dependency values',
      `"foo@npm:^1.0.0":\n  version: 1.0.0\n  resolution: "foo@npm:1.0.0"\n  dependencies:\n    bar:\n      version: 1\n  languageName: node\n  linkType: hard`,
      '"foo@npm:^1.0.0".dependencies.bar must be a string, got a mapping',
    ],
    [
      'flat dependenciesMeta',
      `"foo@npm:^1.0.0":\n  version: 1.0.0\n  resolution: "foo@npm:1.0.0"\n  dependenciesMeta:\n    bar: optional\n  languageName: node\n  linkType: hard`,
      '"foo@npm:^1.0.0".dependenciesMeta.bar must be a mapping, got a string',
    ],
    [
      'unknown linkType',
      `"foo@npm:^1.0.0":\n  version: 1.0.0\n  resolution: "foo@npm:1.0.0"\n  languageName: node\n  linkType: symlink`,
      '"foo@npm:^1.0.0".linkType must be "hard" or "soft", got "symlink"',
    ],
    [
      'malformed checksum',
      `"foo@npm:^1.0.0":\n  version: 1.0.0\n  resolution: "foo@npm:1.0.0"\n  checksum: "sha512-abc=="\n  languageName: node\n  linkType: hard`,
      '"foo@npm:^1.0.0".checksum has an unexpected format: "sha512-abc=="',
    ],
  ])('reports %s', (_, entry, message) => {
    const violations = validateLockfileStructure(
      parseYarnLockfile(lockfileWithEntry(entry)),
    );
    expect(violations.map((v) => v.message)).toEqual([message]);
    expect(violations.every((v) => v.kind === 'type')).toBe(true);
  });
});

describe('findLoopbackReferences', () => {
  it.each([
    'http://localhost:4873/foo/-/foo-1.0.0.tgz',
    'https://LOCALHOST/foo',
    'http://verdaccio.localhost:4873/foo',
    'http://127.0.0.1:4873/foo',
    'http://127.1.2.3/foo',
    'http://0.0.0.0:4873/foo',
    'http://[::1]:4873/foo',
    'http://user:token@localhost:4873/foo',
    // non-conventional tarball URLs are stored URL-encoded in the resolution
    'foo@npm:1.0.0::__archiveUrl=http%3A%2F%2Flocalhost%3A4873%2Ffoo%2F-%2Ffoo-1.0.0.tgz',
    // ... and double-encoded once wrapped in a patch: locator
    'foo@patch:foo@npm%3A1.0.0%3A%3A__archiveUrl%3Dhttp%253A%252F%252F127.0.0.1%253A4873%252Ffoo.tgz#./foo.patch::locator=bar%40workspace%3A.',
    'localhost',
    'localhost:4873',
  ])('detects %s', (value) => {
    expect(findLoopbackReferences(value)).not.toEqual([]);
  });

  it.each([
    'is-localhost-ip@npm:2.0.0',
    'npm:^1.0.0',
    'https://registry.npmjs.org/',
    'https://registry.yarnpkg.com/foo/-/foo-1.0.0.tgz',
    'https://localhost.example.com/foo',
    'http://128.0.0.1/foo',
    '10c0/ef204ca2',
    'malformed %E0%A4%A uri',
  ])('ignores %s', (value) => {
    expect(findLoopbackReferences(value)).toEqual([]);
  });
});

describe('findLockfileLoopbackReferences', () => {
  it('accepts a lockfile without localhost references', () => {
    expect(
      findLockfileLoopbackReferences(parseYarnLockfile(VALID_LOCKFILE)),
    ).toEqual([]);
  });

  it('reports a resolution with a localhost __archiveUrl', () => {
    const lockfile = parseYarnLockfile(
      lockfileWithEntry(`"foo@npm:^1.0.0":
  version: 1.0.0
  resolution: "foo@npm:1.0.0::__archiveUrl=http%3A%2F%2Flocalhost%3A4873%2Ffoo%2F-%2Ffoo-1.0.0.tgz"
  checksum: ${CHECKSUM}
  languageName: node
  linkType: hard`),
    );

    const violations = findLockfileLoopbackReferences(lockfile);

    expect(violations).toEqual([
      expect.objectContaining({
        kind: 'localhost',
        path: '"foo@npm:^1.0.0".resolution',
      }),
    ]);
    expect(violations[0].message).toContain(
      'http://localhost:4873/foo/-/foo-1.0.0.tgz',
    );
  });

  it('reports localhost URLs in descriptors and dependency ranges', () => {
    const lockfile = parseYarnLockfile(
      lockfileWithEntry(`"foo@http://127.0.0.1:4873/foo/-/foo-1.0.0.tgz":
  version: 1.0.0
  resolution: "foo@http://127.0.0.1:4873/foo/-/foo-1.0.0.tgz"
  dependencies:
    bar: "http://localhost:4873/bar/-/bar-1.0.0.tgz"
  languageName: node
  linkType: hard`),
    );

    expect(findLockfileLoopbackReferences(lockfile).map((v) => v.path)).toEqual(
      [
        '"foo@http://127.0.0.1:4873/foo/-/foo-1.0.0.tgz"',
        '"foo@http://127.0.0.1:4873/foo/-/foo-1.0.0.tgz".resolution',
        '"foo@http://127.0.0.1:4873/foo/-/foo-1.0.0.tgz".dependencies.bar',
      ],
    );
  });
});

describe('findYarnrcLoopbackReferences', () => {
  it('accepts the repository .yarnrc.yml', async () => {
    expect(
      findYarnrcLoopbackReferences(
        await readFile(join(REPO_ROOT, '.yarnrc.yml'), 'utf-8'),
      ),
    ).toEqual([]);
  });

  it.each([
    ['npmRegistryServer', 'npmRegistryServer: "http://localhost:4873"'],
    ['unquoted URLs', 'npmPublishRegistry: http://127.0.0.1:4873/'],
    [
      'scoped registries',
      'npmScopes:\n  aws-amplify:\n    npmRegistryServer: "http://localhost:4873"',
    ],
    ['list items', 'unsafeHttpWhitelist:\n  - localhost'],
    ['flow lists', 'unsafeHttpWhitelist: [example.com, "localhost"]'],
  ])('reports %s', (_, content) => {
    const violations = findYarnrcLoopbackReferences(content);
    expect(violations).toHaveLength(1);
    expect(violations[0].kind).toBe('localhost');
  });

  it('ignores comments', () => {
    expect(
      findYarnrcLoopbackReferences(
        '# npmRegistryServer: "http://localhost:4873"\nnodeLinker: node-modules # not localhost:4873\n',
      ),
    ).toEqual([]);
  });
});

describe('LockFileValidator', () => {
  let dir: string;

  beforeEach(async () => {
    dir = await mkdtemp(join(tmpdir(), 'lockfile-validator-'));
  });

  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it('passes for the repository yarn.lock and .yarnrc.yml', async () => {
    const validator = new LockFileValidator(
      join(REPO_ROOT, 'yarn.lock'),
      join(REPO_ROOT, '.yarnrc.yml'),
    );
    await expect(validator.validate()).resolves.toBeUndefined();
  });

  it('passes for a valid lockfile when .yarnrc.yml does not exist', async () => {
    await writeFile(join(dir, 'yarn.lock'), VALID_LOCKFILE);
    const validator = new LockFileValidator(
      join(dir, 'yarn.lock'),
      join(dir, '.yarnrc.yml'),
    );
    await expect(validator.validate()).resolves.toBeUndefined();
  });

  it('fails for a lockfile with a localhost resolution', async () => {
    await writeFile(
      join(dir, 'yarn.lock'),
      VALID_LOCKFILE.replace(
        'resolution: "@actions/core@npm:3.0.0"',
        'resolution: "@actions/core@npm:3.0.0::__archiveUrl=http%3A%2F%2Flocalhost%3A4873%2F%40actions%2Fcore%2F-%2Fcore-3.0.0.tgz"',
      ),
    );
    const validator = new LockFileValidator(
      join(dir, 'yarn.lock'),
      join(dir, '.yarnrc.yml'),
    );

    await expect(validator.validate()).rejects.toThrow(
      /"@actions\/core@npm:\^3\.0\.0"\.resolution value .* points to localhost \(http:\/\/localhost:4873\/@actions\/core\/-\/core-3\.0\.0\.tgz\)/,
    );
    await expect(validator.validate()).rejects.toThrow(/yarn stop:npm-proxy/);
  });

  it('fails when .yarnrc.yml points to a local registry', async () => {
    await writeFile(join(dir, 'yarn.lock'), VALID_LOCKFILE);
    await writeFile(
      join(dir, '.yarnrc.yml'),
      'nodeLinker: node-modules\nnpmRegistryServer: "http://localhost:4873"\n',
    );
    const validator = new LockFileValidator(
      join(dir, 'yarn.lock'),
      join(dir, '.yarnrc.yml'),
    );

    await expect(validator.validate()).rejects.toThrow(
      /\.yarnrc\.yml line 2 points to localhost/,
    );
  });

  it('fails for a lockfile that cannot be parsed', async () => {
    // e.g. a package-lock.json renamed or committed in place of yarn.lock
    await writeFile(join(dir, 'yarn.lock'), '{\n  "lockfileVersion": 3\n}\n');
    const validator = new LockFileValidator(
      join(dir, 'yarn.lock'),
      join(dir, '.yarnrc.yml'),
    );

    await expect(validator.validate()).rejects.toThrow(/could not be parsed/);
  });

  it('fails for a lockfile with invalid value types', async () => {
    await writeFile(
      join(dir, 'yarn.lock'),
      VALID_LOCKFILE.replace(
        '  linkType: soft',
        '  linkType:\n    value: soft',
      ),
    );
    const validator = new LockFileValidator(
      join(dir, 'yarn.lock'),
      join(dir, '.yarnrc.yml'),
    );

    await expect(validator.validate()).rejects.toThrow(
      /"amplify-data-monorepo@workspace:\."\.linkType must be a string, got a mapping/,
    );
  });
});
